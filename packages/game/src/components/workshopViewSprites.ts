export const WORKSHOP_VIEW_SPRITE_TEMPLATES: Readonly<Record<WorkshopViewId, PixelTemplate>> =
  TEMPLATES

/**
 * Each backdrop's authored dimensions, derived from its own template so the
 * two can never disagree. One authored size only, which
 * `workshopViewSprites.test.ts` pins along with the width of every row: a
 * short row does not fail, it silently shifts every pixel after it.
 */
export const WORKSHOP_VIEW_SPRITE_GRID: Readonly<Record<WorkshopViewId, { w: number; h: number }>> =
  Object.fromEntries(
    (Object.keys(TEMPLATES) as WorkshopViewId[]).map((id) => [id, templateGrid(TEMPLATES[id])]),
  ) as Record<WorkshopViewId, { w: number; h: number }>

/**
 * Rasterise a view backdrop to a PNG data URL for the DOM. Returns '' when no
 * template exists. Memoised per (view, scale); the key is prefixed because the
 * raster cache is shared with the part sprites, whose ids live in a different
 * namespace and could otherwise collide.
 */
export function workshopViewDataUrl(viewId: WorkshopViewId, scale = 4): string {
  const template = TEMPLATES[viewId] as PixelTemplate | undefined
  if (!template) return ''
  return rasterise(template, PART_SPRITE_PALETTE, scale, `workshopView:${viewId}:${scale}`)
}
